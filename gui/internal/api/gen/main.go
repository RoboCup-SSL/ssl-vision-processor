// Command gen writes comments_gen.go: the Go doc comment of every exported
// type and struct field in the packages whose types the API serves, keyed by
// import path, type and field, for api.describe to put in the spec. Run by
// `go generate ./internal/api`.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const module = "github.com/RoboCup-SSL/ssl-vision-processor/gui"

// dirs are relative to internal/api, where go generate runs.
var dirs = []string{
	"../alerts", "../config", "../detections", "../geometry", "../httpjson",
	"../multicast", "../referee", "../snapshot", "../supervisor", "../v4l",
	"../../cmd/ssl-vision-processor-gui",
}

// mainPackage is the import path of the dir holding package main, which a
// built binary reports as just "main".
var mainPackage string

func main() {
	comments := map[string]string{}
	fset := token.NewFileSet()

	for _, dir := range dirs {
		files, err := filepath.Glob(filepath.Join(dir, "*.go"))
		if err != nil {
			log.Fatal(err)
		}

		for _, path := range files {
			if strings.HasSuffix(path, "_test.go") {
				continue
			}

			f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
			if err != nil {
				log.Fatal(err)
			}

			pkg := module + "/" + filepath.ToSlash(filepath.Clean(filepath.Join("internal/api", dir)))
			if f.Name.Name == "main" {
				mainPackage = pkg
			}

			collect(comments, pkg, f)
		}
	}

	keys := make([]string, 0, len(comments))
	for k := range comments {
		keys = append(keys, k)
	}

	sort.Strings(keys)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by go run ./gen; DO NOT EDIT.\n\npackage api\n\n")
	fmt.Fprintf(&buf, "// mainPackage is package main's import path, which a built binary reports\n// as just \"main\".\nconst mainPackage = %q\n\n", mainPackage)
	buf.WriteString("// comments are Go doc comments by import path, type and field.\nvar comments = map[string]string{\n")

	for _, k := range keys {
		fmt.Fprintf(&buf, "\t%q: %q,\n", k, comments[k])
	}

	buf.WriteString("}\n")

	out, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}

	if err := os.WriteFile("comments_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func collect(comments map[string]string, pkg string, f *ast.File) {
	for _, decl := range f.Decls {
		// Functions and methods, keyed as the runtime names them:
		// main.(*VisionServer).getConfig.
		if fn, ok := decl.(*ast.FuncDecl); ok {
			if doc := lead(fn.Name.Name, text(fn.Doc)); doc != "" {
				comments[pkg+"."+funcName(fn)] = doc
			}

			continue
		}

		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}

		for _, spec := range gen.Specs {
			ts := spec.(*ast.TypeSpec)

			doc := text(ts.Doc)
			if doc == "" && len(gen.Specs) == 1 {
				doc = text(gen.Doc)
			}

			doc = lead(ts.Name.Name, doc)

			key := pkg + "." + ts.Name.Name
			if doc != "" {
				comments[key] = doc
			}

			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				continue
			}

			for _, field := range st.Fields.List {
				doc := strings.TrimSpace(text(field.Doc) + " " + text(field.Comment))
				if doc == "" {
					continue
				}

				for _, name := range field.Names {
					comments[key+"."+name.Name] = lead(name.Name, doc)
				}
			}
		}
	}
}

func funcName(fn *ast.FuncDecl) string {
	if fn.Recv == nil || len(fn.Recv.List) == 0 {
		return fn.Name.Name
	}

	switch t := fn.Recv.List[0].Type.(type) {
	case *ast.StarExpr:
		if id, ok := t.X.(*ast.Ident); ok {
			return "(*" + id.Name + ")." + fn.Name.Name
		}
	case *ast.Ident:
		return t.Name + "." + fn.Name.Name
	}

	return fn.Name.Name
}

// lead rewrites a Go doc comment's opening for an API reader: "Document is
// one vision.yml." becomes "One vision.yml.", "Params are the facts" becomes
// "The facts".
func lead(name, doc string) string {
	rest, ok := strings.CutPrefix(doc, name+" ")
	if !ok || rest == "" {
		return doc
	}

	for _, verb := range []string{"is ", "are "} {
		if r, ok := strings.CutPrefix(rest, verb); ok {
			rest = r

			break
		}
	}

	return strings.ToUpper(rest[:1]) + rest[1:]
}

// text is a comment group as one paragraph: what a spec description wants.
func text(g *ast.CommentGroup) string {
	if g == nil {
		return ""
	}

	return strings.Join(strings.Fields(g.Text()), " ")
}
